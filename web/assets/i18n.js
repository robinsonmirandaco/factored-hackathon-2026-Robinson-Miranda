const LOCALES = { es: "es-MX", pt: "pt-BR" };

export function translator(lang) {
  const table = TEXT[lang] || TEXT.es;
  return (key, vars = {}) => {
    const text = table[key] ?? TEXT.es[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
  };
}

// A label for a code the API returns, or the code itself when there is no translation.
export function label(t, prefix, code) {
  const key = `${prefix}_${code}`;
  const text = t(key);
  return text === key ? code : text;
}

export function money(lang, amount, currency) {
  try {
    // Always the cents of the record: Intl drops them for COP, which would show 257.21 as 257.
    return new Intl.NumberFormat(LOCALES[lang], {
      style: "currency", currency, minimumFractionDigits: 2, maximumFractionDigits: 2,
    }).format(amount);
  } catch {
    return `${amount} ${currency}`;
  }
}

// A number with no currency, such as an amount the customer gave without one.
export function number(lang, value) {
  return new Intl.NumberFormat(LOCALES[lang]).format(value);
}

// "2026-06-10" and "2026-06-10T14:22:00" are dates of the records, without a time zone: they
// are read as written, never shifted to the browser's zone.
function parts(iso) {
  const [d, time = "00:00"] = String(iso).split("T");
  const [y, m, day] = d.split("-").map(Number);
  const [hh, mm] = time.split(":").map(Number);
  return new Date(Date.UTC(y, m - 1, day, hh || 0, mm || 0));
}

// Month abbreviations come with a point in some locales ("jun."), not in others: none is kept,
// so every date of the screens reads the same way.
const noPoint = (text) => text.replace(/\./g, "");

export function day(lang, iso) {
  return noPoint(new Intl.DateTimeFormat(LOCALES[lang], {
    day: "numeric",
    month: "short",
    year: "numeric",
    timeZone: "UTC",
  }).format(parts(iso)));
}

export function dayMonth(lang, iso) {
  return noPoint(new Intl.DateTimeFormat(LOCALES[lang], {
    day: "numeric",
    month: "short",
    timeZone: "UTC",
  }).format(parts(iso)));
}

export function dayTime(lang, iso) {
  return noPoint(new Intl.DateTimeFormat(LOCALES[lang], {
    day: "numeric",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    hourCycle: "h23",
    timeZone: "UTC",
  }).format(parts(iso)));
}
